def replace_paragraph_text(paragraph, new_text: str) -> None:
    if paragraph.runs:
        paragraph.runs[0].text = new_text
        for run in paragraph.runs[1:]:
            run.text = ""
    else:
        paragraph.add_run(new_text)


def create_story_doc(source: Path, output: Path) -> None:
    document = Document(source)
    seen = set()
    for paragraph in document.paragraphs:
        original = paragraph.text
        if original in REPLACEMENTS:
            replace_paragraph_text(paragraph, REPLACEMENTS[original])
            seen.add(original)

    missing = sorted(set(REPLACEMENTS) - seen)
    if missing:
        raise RuntimeError("The following source paragraphs were not found:\n" + "\n".join(missing))

    document.add_paragraph("---")
    document.add_paragraph("剧情逻辑统一说明")
    for text in (
        "女主角姓氏统一为“林”；节目单与窗台刻字同步改为林氏女。",
        "簪首由委托人从旧货市场收回；簪尾由林氏女离开前藏入郑家大屋暗格，第三章由玩家找到。",
        "雨夜等待发生在前，林氏女回家后父亲才当面折断发簪。",
        "隐藏铭文统一为“簪合即归”，由林氏女离开澳门前刻下。",
        "第三章只出现第三段铭文的模糊提示，第四章才正式获得“勿失勿忘”。",
        "结局顺序统一为C＞A＞B＞D，所有已拼合与未拼合情况均有对应结局。",
    ):
        document.add_paragraph("· " + text)

    output.parent.mkdir(parents=True, exist_ok=True)
    document.save(output)
    print(output)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="保留原稿，另存一份剧情逻辑统一后的 Word 副本。"
    )
    parser.add_argument("source", type=Path, help="B 成员原 Word 文件路径")
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="修改后副本的保存路径",
    )
    args = parser.parse_args()
    create_story_doc(args.source, args.output)


if __name__ == "__main__":
    main()
